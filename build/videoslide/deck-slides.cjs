#!/usr/bin/env node
// Writes js/cm-deck-slides.js from build/videoslide/dayN.json: which deck pages stand in for each lesson's slides,
// each page's title and speaker notes (Presenter view), and the day's narrated video with one chapter per page; and,
// from build/debrief/debrief.json, the Case Debrief's video and slides (CM_DEBRIEF_VIDEO).
//   node build/videoslide/deck-slides.cjs
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..", "..");
const lessons = {}, videos = {};
for (const f of fs.readdirSync(__dirname).filter((x) => /^day\d+\.json$/.test(x)).sort()) {
  const d = JSON.parse(fs.readFileSync(path.join(__dirname, f), "utf8")), n = f.match(/\d+/)[0];
  const by = new Map(d.slides.map((s) => [s.page, s]));
  const img = (p) => `/decks/day${n}/${String(p).padStart(2, "0")}.webp`;
  for (const [block, pages] of Object.entries(d.lessons || {})) {
    if (lessons[block]) throw new Error(`${f}: lesson ${block} is named by two decks' notes`);
    lessons[block] = pages.map((p) => {
      const s = by.get(p); if (!s) throw new Error(`${f}: lesson ${block} names page ${p}, which has no notes`);
      if (!fs.existsSync(path.join(ROOT, img(p)))) throw new Error(`${f}: ${img(p)} is missing`);
      return { page: p, title: s.title, img: img(p), notes: s.notes };
    });
  }
  // (no "onDeck" any more: a deck page is a lesson's slide, on the day that lesson is taught: .github/scripts/day-decks.cjs)
  if (d.onDeck) throw new Error(`${f}: "onDeck" is gone: name the lesson each page teaches in "lessons"`);
  if (d.video) {
    const inVideo = d.slides;   // the video is the deck, page for page
    if (d.video.starts.length !== inVideo.length) throw new Error(`${f}: video.starts needs one time per slide in the video (${inVideo.length})`);
    videos[d.day] = { title: d.title, src: d.video.src, captions: d.video.captions,
      chapters: inVideo.map((s, i) => ({ t: d.video.starts[i], page: s.page, title: s.title })) };
  }
}
// The Case Debrief (build/debrief/debrief.json, drawn by build/debrief/render.cjs): its video and one chapter per slide,
// for the 🎬 Case Debrief tab on the Case Profile (js/cm-case-debrief.js). "recorded" once video.starts has a time for
// every slide (make_video.py prints them); until then the tab steps through the slides and their script.
const debrief = (() => {
  const f = path.join(ROOT, "build", "debrief", "debrief.json"); if (!fs.existsSync(f)) return null;
  const d = JSON.parse(fs.readFileSync(f, "utf8")), v = d.video || {}, starts = v.starts || [];
  if (starts.length && starts.length !== d.slides.length) throw new Error(`build/debrief/debrief.json: video.starts needs one time per slide (${d.slides.length}), or none until the video is recorded`);
  const img = (p) => `/decks/debrief/${String(p).padStart(2, "0")}.webp`;
  d.slides.forEach((s) => { if (!fs.existsSync(path.join(ROOT, img(s.page)))) throw new Error(`build/debrief/debrief.json: ${img(s.page)} is missing (node build/debrief/render.cjs)`); });
  return { title: d.title, src: v.src, captions: v.captions, poster: img(d.slides[0].page), opensAfter: d.opensAfter || 5, recorded: starts.length === d.slides.length,
    chapters: d.slides.map((s, i) => ({ t: starts.length ? starts[i] : null, page: s.page, title: s.title, img: img(s.page), notes: s.notes })) };
})();
const out = `/* GENERATED by build/videoslide/deck-slides.cjs from build/videoslide/dayN.json and build/debrief/debrief.json. Do not edit by hand.
   CM_DECK_SLIDES: block id -> the Canva deck pages shown as that lesson's slides (js/cm-case-flow.js viewsOf).
   CM_DAY_VIDEOS: day id -> the day's narrated video and its chapters (js/cm-day-video.js).
   CM_DEBRIEF_VIDEO: the Case Debrief's narrated video, one chapter per slide (js/cm-case-debrief.js).
 */
window.CM_DECK_SLIDES = ${JSON.stringify(lessons, null, 1)};
window.CM_DAY_VIDEOS = ${JSON.stringify(videos, null, 1)};
window.CM_DEBRIEF_VIDEO = ${JSON.stringify(debrief, null, 1)};
`;
fs.writeFileSync(path.join(ROOT, "js", "cm-deck-slides.js"), out);
console.log(`js/cm-deck-slides.js: ${Object.keys(lessons).length} lessons, ${Object.values(lessons).reduce((a, x) => a + x.length, 0)} deck slides, ${Object.keys(videos).length} video(s)${debrief ? `, the Case Debrief (${debrief.chapters.length} slides, ${debrief.recorded ? "recorded" : "not recorded yet"})` : ""}`);
