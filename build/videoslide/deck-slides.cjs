#!/usr/bin/env node
// Writes js/cm-deck-slides.js from build/videoslide/dayN.json: which deck pages stand in for each lesson's slides,
// each page's title and speaker notes (Presenter view), and the day's narrated video with one chapter per page.
//   node build/videoslide/deck-slides.cjs
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..", "..");
const lessons = {}, videos = {};
for (const f of fs.readdirSync(__dirname).filter((x) => /^day\d+\.json$/.test(x)).sort()) {
  const d = JSON.parse(fs.readFileSync(path.join(__dirname, f), "utf8")), n = f.match(/\d+/)[0];
  const by = new Map(d.slides.map((s) => [s.page, s]));
  const img = (p) => `/decks/day${n}/${String(p).padStart(2, "0")}.webp`;
  for (const [block, pages] of Object.entries(d.lessons || {})) {
    lessons[block] = pages.map((p) => {
      const s = by.get(p); if (!s) throw new Error(`${f}: lesson ${block} names page ${p}, which has no notes`);
      if (!fs.existsSync(path.join(ROOT, img(p)))) throw new Error(`${f}: ${img(p)} is missing`);
      return { page: p, title: s.title, img: img(p), notes: s.notes };
    });
  }
  if (d.video) {
    const inVideo = d.slides;   // the video is the deck, page for page
    if (d.video.starts.length !== inVideo.length) throw new Error(`${f}: video.starts needs one time per slide in the video (${inVideo.length})`);
    videos[d.day] = { title: d.title, src: d.video.src, captions: d.video.captions,
      chapters: inVideo.map((s, i) => ({ t: d.video.starts[i], page: s.page, title: s.title })) };
  }
}
const out = `/* GENERATED by build/videoslide/deck-slides.cjs from build/videoslide/dayN.json. Do not edit by hand.
   CM_DECK_SLIDES: block id -> the Canva deck pages shown as that lesson's slides (js/cm-case-flow.js viewsOf).
   CM_DAY_VIDEOS: day id -> the day's narrated video and its chapters (js/cm-day-video.js). */
window.CM_DECK_SLIDES = ${JSON.stringify(lessons, null, 1)};
window.CM_DAY_VIDEOS = ${JSON.stringify(videos, null, 1)};
`;
fs.writeFileSync(path.join(ROOT, "js", "cm-deck-slides.js"), out);
console.log(`js/cm-deck-slides.js: ${Object.keys(lessons).length} lessons, ${Object.values(lessons).reduce((a, x) => a + x.length, 0)} deck slides, ${Object.keys(videos).length} video(s)`);
