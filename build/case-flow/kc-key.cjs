#!/usr/bin/env node
/* The Knowledge Check key the Worker scores a trainee's attempt with: worker-kc-key.js, from js/cm-case-flow-data.js.

     node build/case-flow/kc-key.cjs            writes worker-kc-key.js (build/case-flow/build.cjs runs it)
     node build/case-flow/kc-key.cjs --check    writes nothing; exit 1 when worker-kc-key.js is not what it would write

   Each Case Flow day's Knowledge Check is built by the page (js/cm-case-flow.js, "every day's Knowledge Check: 20
   questions"): the day's sequence, in order; each Knowledge Check block there brings its module's quiz; the questions
   are taken in turn from each module until there are 20, kept in the order they are taught. This builds the same list,
   and keeps of it only what the Worker needs: each question's right option (a) and its module (mod), so the Worker can
   score the first attempt from its own picks (worker-identity.js kcScore) and work out each module's share of it. A
   trainer's published extra questions (extraquiz:day<N>) follow these on the page; the Worker reads those from KV.
   Two checks hold the page and this file to the same list: .github/scripts/kc-key-page.cjs (browser: the page's quizzes
   are this key) and .github/scripts/kc-score.cjs (node: runs this file with --check). It is a generated file (merge-main's
   GENERATED list): never edit worker-kc-key.js by hand, run this. worker-*.js is kept out of the published
   site (.assetsignore). */
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "../..");
const OUT = path.join(ROOT, "worker-kc-key.js");
const QUIZ_N = 20;   // (js/cm-case-flow.js QUIZ_N)

global.window = {};
require(path.join(ROOT, "js/cm-case-flow-data.js"));
const CF = global.window.CM_CASE_FLOW;

function kcKey(CF){
  const STORED = {};
  CF.days.forEach(day => day.modules.forEach(mod => mod.blocks.forEach(b => { STORED[b.id] = {day, mod, block: b}; })));
  const SEQUENCE = Array.isArray(CF.sequence) && CF.sequence.length ? CF.sequence
    : CF.days.map(day => ({n: day.n, phases: day.modules.map(m => ({blocks: ["lesson", "activity", "check"].flatMap(kind => m.blocks.filter(b => b.kind === kind).map(b => b.id))}))}));
  const out = {};
  SEQUENCE.forEach(seq => {
    const day = CF.days.find(x => x.n === seq.n); if(!day) return;
    const pools = [];
    seq.phases.forEach(ph => ph.blocks.forEach(id => { const at = STORED[id]; if(at && at.block.kind === "check") pools.push((at.mod.quiz || []).map(q => ({q, mod: at.mod.id}))); }));
    const take = pools.map(() => 0); let left = Math.min(QUIZ_N, pools.reduce((a, p) => a + p.length, 0));
    for(let k = 0; left; k = (k + 1) % pools.length) if(take[k] < pools[k].length){ take[k]++; left--; }
    const picked = pools.flatMap((p, k) => p.slice(0, take[k]));
    out[String(day.id)] = {a: picked.map(x => x.q.a), mod: picked.map(x => x.mod)};
  });
  return out;
}
const key = kcKey(CF);
Object.entries(key).forEach(([d, k]) => { if(!k.a.length || k.a.some(a => !Number.isInteger(a))) { console.error(`Day ${d}: a Knowledge Check question has no right option (a).`); process.exit(1); } });
const text = `/* Generated by build/case-flow/kc-key.cjs from js/cm-case-flow-data.js: never edit by hand (node build/case-flow/build.cjs).
   Each Case Flow day's Knowledge Check, as the page builds it: each question's right option (a) and its module (mod).
   worker-identity.js scores a trainee's attempt from its own picks with it. Not published (.assetsignore: worker-*.js). */
export const KC_KEY = ${JSON.stringify(key)};
`;
if(process.argv.includes("--check")){
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if(cur !== text){ console.error("worker-kc-key.js is not in step with js/cm-case-flow-data.js: run node build/case-flow/build.cjs."); process.exit(1); }
  console.log("worker-kc-key.js is in step with the lesson data.");
} else {
  const was = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  fs.writeFileSync(OUT, text);
  console.log(`${was === text ? "unchanged" : "wrote"} worker-kc-key.js (${Object.keys(key).length} days, ${Object.values(key).map(k => k.a.length).join("/")} questions)`);
}
