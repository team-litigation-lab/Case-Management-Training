#!/usr/bin/env node
/* Every version the course has ever served of each case document, by its bytes: worker-drive-versions.js, the MD5 of
   each version of documents/<file> (js/cm-case-flow-docs.js) in the git history and in the working tree. The Backup
   Drive grader (worker-drive-found.js) knows a file on the trainee's drive by Google Drive's md5Checksum, so a trainee
   who backed up a document before it was re-rendered (RS12 on 2026-11-18, and every later re-render) still has that
   document, by its bytes; bytes that are no version of any course document are still no document.
     node build/case-flow/documents/versions.cjs           adds any version not yet listed (run by build.cjs)
     node build/case-flow/documents/versions.cjs --check   fails when a version in reach is not listed
   The list only grows: a version once listed is never dropped, so the file is committed data, and a shallow checkout
   (CI's) that sees only today's files leaves it as it is. It reads git and the files on disk, never the network.
   A file under a kilobyte is no course document (worker-drive-found.js MIN_DOC_BYTES) and is never listed. */
"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto"), { spawnSync } = require("child_process");
const ROOT = path.resolve(__dirname, "../../.."), CHECK = process.argv.includes("--check");
const OUT = path.join(ROOT, "worker-drive-versions.js");
const MIN_BYTES = 1024;   // as worker-drive-found.js MIN_DOC_BYTES
global.window = global.window || {};
require(path.join(ROOT, "js/cm-case-flow-docs.js"));
const DOCS = window.CM_CF_DOCS.filter((d) => d && d.id && d.file);
const md5 = (b) => crypto.createHash("md5").update(b).digest("hex");

// what is listed already (never dropped)
const parse = (src) => { const m = /DOC_VERSIONS = (\{[\s\S]*?\n\});/.exec(src || ""); return m ? JSON.parse(m[1]) : {}; };
const had = fs.existsSync(OUT) ? parse(fs.readFileSync(OUT, "utf8")) : {};
const got = {}; Object.entries(had).forEach(([id, hs]) => { got[id] = new Set(hs); });
const add = (id, b) => { if (b && b.length >= MIN_BYTES) (got[id] = got[id] || new Set()).add(md5(b)); };

// every version in this checkout's history (a shallow one has only its own): one git log over documents/, each commit
// against each parent (-m, so a version a merge settled on is there too), the root as added (--root)
const git = (args, opts = {}) => spawnSync("git", args, Object.assign({ cwd: ROOT, maxBuffer: 1 << 30 }, opts));
const top = git(["rev-parse", "--show-toplevel"], { encoding: "utf8" });
if (top.status === 0 && path.resolve(top.stdout.trim()) === ROOT) {
  const idOf = {}; DOCS.forEach((d) => { (idOf["documents/" + d.file] = idOf["documents/" + d.file] || []).push(d.id); });
  const log = git(["log", "--full-history", "-m", "--root", "--raw", "--no-abbrev", "--no-renames", "--format=", "--", "documents/"], { encoding: "utf8" });
  if (log.status !== 0) { console.error("git log failed: " + log.stderr); process.exit(1); }
  const blobs = new Map();   // blob id -> [docId]
  log.stdout.split("\n").forEach((l) => {
    const m = /^:\d+ \d+ [0-9a-f]+ ([0-9a-f]{40}) [AMTC]\d*\t(.+)$/.exec(l);
    if (m && idOf[m[2]] && !/^0+$/.test(m[1])) blobs.set(m[1], idOf[m[2]]);
  });
  if (blobs.size) {
    const ids = [...blobs.keys()];
    const cat = git(["cat-file", "--batch"], { input: ids.join("\n") + "\n" });
    if (cat.status !== 0) { console.error("git cat-file failed: " + String(cat.stderr)); process.exit(1); }
    const buf = cat.stdout; let at = 0;
    for (const id of ids) {
      const nl = buf.indexOf(10, at), head = buf.subarray(at, nl).toString().split(" ");
      if (head[1] === "missing") { at = nl + 1; continue; }
      const size = Number(head[2]), body = buf.subarray(nl + 1, nl + 1 + size);
      at = nl + 1 + size + 1;
      blobs.get(id).forEach((docId) => add(docId, body));
    }
  }
}
// and the files as they are on disk now (a re-render not yet committed)
DOCS.forEach((d) => { const f = path.join(ROOT, "documents", d.file); if (fs.existsSync(f)) add(d.id, fs.readFileSync(f)); });

const ordered = Object.keys(got).filter((id) => got[id].size).sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
const body = "{\n" + ordered.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify([...got[id]].sort())}`).join(",\n") + "\n}";
const src = `/* GENERATED by build/case-flow/documents/versions.cjs (node build/case-flow/build.cjs): do not edit by hand.
   Every version the course has served of each case document, by the MD5 of its bytes (Google Drive's md5Checksum of a
   file uploaded with those bytes). worker-drive-found.js knows a file on a trainee's Backup Drive with any of them as
   that document. The list only grows: a version once listed is never dropped. */
export const DOC_VERSIONS = ${body};
`;
const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
const count = ordered.reduce((n, id) => n + got[id].size, 0);
if (CHECK) {
  if (now !== src) { console.error("worker-drive-versions.js is out of step with the course's documents: run node build/case-flow/build.cjs and commit it."); process.exit(1); }
  console.log(`Document versions in step: ${count} versions of ${ordered.length} documents in worker-drive-versions.js.`);
} else if (now !== src) { fs.writeFileSync(OUT, src); console.log(`wrote worker-drive-versions.js: ${count} versions of ${ordered.length} documents`); }
else console.log(`worker-drive-versions.js: ${count} versions of ${ordered.length} documents, none new`);
